def cmd_render_dc(path, out_file, canvas=None):
    d = load(path)
    ph = phases(d)
    exists_label = "Exists" if LANG == "en" else "มีแล้ว"
    data = {
        "title": d.get("title", ""),
        "asOf": d.get("asOf", ""),
        "lang": LANG,
        "summary": d.get("summary", ""),
        "phases": ph,
        "phaseShort": dict({k: short_label(v) for k, v in ph.items()}, X=exists_label),
        "screens": {k: {"file": v.get("file")} for k, v in (d.get("screens") or {}).items()
                    if isinstance(v, dict) and v.get("drawn", True) and v.get("file")},
        "groups": [
            {"title": g.get("title", ""), "lead": g.get("lead", ""),
             "features": [dict({k: ft[k] for k in ("name", "desc", "screens", "seen") if k in ft},
                               pr="X" if is_exists(ft) else ft.get("pr"))
                          for ft in g.get("features", [])]}
            for g in d.get("groups", [])
        ],
        "questions": [{k: q[k] for k in ("text", "owner", "due") if k in q} for q in d.get("questions") or []],
        "decisions": [{k: x[k] for k in ("topic", "decision", "why") if k in x} for x in d.get("decisions") or []],
        "sources": [{k: s[k] for k in ("text", "url") if k in s} for s in d.get("sources") or []],
    }
    n = sum(len(g["features"]) for g in data["groups"])
    height = 60 * n + 110 * len(data["groups"]) + 30 * (len(data["questions"]) + len(data["decisions"])) + 900
    js = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    html = TEMPLATE.read_text(encoding="utf-8")
    html = html.replace("/*__DATA__*/null", js).replace("__HEIGHT__", str(height)).replace("__LANG__", LANG)
    out = Path(out_file)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    print(m("dc_wrote", f=out, n=n, h=height))
    if canvas:
        cp = Path(canvas)
        c = json.loads(cp.read_text(encoding="utf-8"))
        key = out.name
        try:
            key = str(out.resolve().relative_to(cp.resolve().parent))
        except ValueError:
            pass
        board = (c.get("boards") or {}).get(key)
        if board is None:
            print(m("dc_noboard", c=cp, b=key))
        else:
            board["h"] = height
            cp.write_text(json.dumps(c, ensure_ascii=False, indent=2), encoding="utf-8")
            print(m("dc_canvas", b=key, c=cp, h=height))
    return 0


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    flags = [a for a in argv[1:] if a.startswith("--")]
    canvas = None
    if "--canvas" in argv:
        i = argv.index("--canvas")
        if i + 1 < len(argv):
            canvas = argv[i + 1]
            args = [a for a in args if a != canvas]
    if not args:
        print(__doc__)
        return 2
    cmd = args[0]
    if cmd == "check" and len(args) == 2:
        return cmd_check(args[1])
    if cmd == "render-md" and len(args) == 3:
        return cmd_render_md(args[1], args[2], force="--force" in flags)
    if cmd == "render-dc" and len(args) == 3:
        return cmd_render_dc(args[1], args[2], canvas)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
