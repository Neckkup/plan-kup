#!/usr/bin/env python3
"""Check and render a plan-kup features.json

  features.py check      <features.json>
  features.py render-md  <features.json> <out-dir> [--force]
  features.py render-dc  <features.json> <out-file.dc.html> [--canvas <canvas.json>]

check exits 1 when there is an ERROR.
render-md refuses to overwrite a file it did not generate unless --force is given.
render-dc with --canvas also updates that board's height in canvas.json.
Messages follow the "lang" field of features.json (th or en).
"""
