def m(key, **kw):
    th, en = MSG[key]
    return (en if LANG == "en" else th).format(**kw)


def load(path):
    global LANG
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    LANG = d.get("lang", "th")
    return d


def all_features(d):
    for g in d.get("groups", []):
        for ft in g.get("features", []):
            yield g, ft


def is_exists(ft):
    return ft.get("status") == "exists"


def short_label(full):
    """'MVP (~3 เดือน)' -> 'MVP', 'Phase 2: AI' -> 'Phase 2'"""
    for sep in (" (", ":", " —", " -"):
        if sep in full:
            full = full.split(sep)[0]
    return full.strip()


def phases(d):
    base = dict(DEFAULT_PHASES)
    base.update(d.get("phases") or {})
    return base


def budget_points(d):
    """Return (points or None, explanation or None)."""
    b = d.get("mvpBudget") or {}
    if "points" in b:
        return b["points"], None
    if "weeks" in b and "devs" in b:
        o = b.get("overhead", DEFAULT_OVERHEAD)
        r = b.get("pointsPerDevWeek", POINTS_PER_DEV_WEEK)
        pts = int(b["weeks"] * b["devs"] * r * (1 - o))
        return pts, m("budget_calc", w=b["weeks"], d=b["devs"], r=r, o=o, b=pts)
    return None, None


# ---------------------------------------------------------------- check

def check(d):
    errors, warns, infos = [], [], []
    feats = {}
    screens = d.get("screens") or {}

    for k in ("title", "asOf", "groups"):
        if k not in d:
            errors.append(m("missing_top", k=k))

    for g, ft in all_features(d):
        fid = ft.get("id")
        where = f"[{g.get('title', '?')}] {ft.get('name', '?')}"
        if not fid:
            errors.append(m("no_id", w=where))
            continue
        if fid in feats:
            errors.append(m("dup_id", i=fid))
        feats[fid] = (g, ft)
        if not is_exists(ft) and ft.get("pr") not in RANK:
            errors.append(m("bad_pr", i=fid, p=ft.get("pr")))
        for k in ("name", "desc"):
            if not ft.get(k):
                warns.append(m("no_field", i=fid, k=k))
        if ft.get("size") and ft["size"] not in SIZE_POINTS:
            errors.append(m("bad_size", i=fid, s=ft["size"]))
        for s in ft.get("screens") or []:
            if s != "all" and s not in screens:
                errors.append(m("bad_screen", i=fid, s=s))

    for fid, (g, ft) in feats.items():
        if is_exists(ft):
            continue
        pr = ft.get("pr")
        for dep in ft.get("dependsOn") or []:
            if dep not in feats:
                errors.append(m("bad_dep", i=fid, d=dep))
                continue
            dft = feats[dep][1]
            if is_exists(dft):
                continue
            dpr = dft.get("pr")
            if pr in RANK and dpr in RANK and RANK[dpr] > RANK[pr]:
                errors.append(m("dep_order", i=fid, p=pr, d=dep, dp=dpr))

    by_name = defaultdict(list)
    for fid, (g, ft) in feats.items():
        by_name[(ft.get("name") or "").strip().lower()].append((fid, ft.get("pr"), g.get("title")))
    for name, items in by_name.items():
        if name and len(items) > 1:
            detail = ", ".join(f"{i} ({p}, {t})" for i, p, t in items)
            if len({p for _, p, _ in items}) > 1:
                errors.append(m("name_pr", x=detail))
            else:
                warns.append(m("name_dup", x=detail))

    noscreen = [fid for fid, (g, ft) in feats.items()
                if ft.get("pr") == "M" and ft.get("ui", True) and not is_exists(ft) and not ft.get("screens")]
    if noscreen:
        warns.append(m("mvp_noscreen", n=len(noscreen), x=", ".join(noscreen)))

    screen_prs = defaultdict(lambda: defaultdict(list))
    for fid, (g, ft) in feats.items():
        if is_exists(ft):
            continue
        for s in ft.get("screens") or []:
            screen_prs[s][ft.get("pr")].append(fid)
    planned = []
    for s, meta in screens.items():
        meta = meta if isinstance(meta, dict) else {}
        drawn = meta.get("drawn", True)
        if not drawn:
            planned.append(s)
        elif not meta.get("file"):
            errors.append(m("screen_nofile", s=s))
        prs = screen_prs.get(s)
        if not prs:
            infos.append(m("screen_unused", s=s))
        elif not set(prs) & {"M", "P1"}:
            warns.append(m("screen_late", s=s, p="/".join(sorted(prs))))
        elif "M" in prs and set(prs) & {"P2", "L"} and drawn:
            late = sorted(set(prs) & {"P1", "P2", "L"})
            ids = [i for p in late for i in prs[p]]
            infos.append(m("screen_mixed", s=s, p="/".join(late), x=", ".join(ids)))
    if planned:
        infos.append(m("planned", n=len(planned), x=", ".join(planned)))

    for i, q in enumerate(d.get("questions") or [], 1):
        if not q.get("text"):
            errors.append(m("q_text", n=i))
        for a in q.get("affects") or []:
            if a not in feats:
                errors.append(m("q_aff", n=i, a=a))
        if not q.get("owner"):
            warns.append(m("q_owner", n=i))

    counts = defaultdict(int)
    points = defaultdict(int)
    for fid, (g, ft) in feats.items():
        if is_exists(ft):
            counts["exists"] += 1
            continue
        pr = ft.get("pr")
        counts[pr] += 1
        points[pr] += SIZE_POINTS.get(ft.get("size") or "M", 3)
    b = d.get("mvpBudget") or {}
    bp, how = budget_points(d)
    if how:
        infos.append(how)
    if "count" in b and counts["M"] > b["count"]:
        warns.append(m("budget_count", n=counts["M"], b=b["count"]))
    if bp is not None and points["M"] > bp:
        warns.append(m("budget_pts", n=points["M"], b=bp))
    if not b:
        infos.append(m("budget_none"))

    return errors, warns, infos, counts, points


def cmd_check(path):
    d = load(path)
    errors, warns, infos, counts, points = check(d)
    total = sum(counts[p] for p in PRS) + counts["exists"]
    print(m("total", n=total))
    for p in PRS:
        print(m("row", p=p, c=counts[p], t=points[p]))
    if counts["exists"]:
        print(m("exists", n=counts["exists"]))
    for label, items in (("ERROR", errors), ("WARN", warns), ("INFO", infos)):
        for x in items:
            print(f"{label}: {x}")
    print("\n" + m("tally", e=len(errors), w=len(warns), i=len(infos)))
    return 1 if errors else 0


