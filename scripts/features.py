def esc(s):
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def cmd_render_md(path, out_dir, force=False):
    d = load(path)
    t = L.get(LANG, L["th"])
    ph = phases(d)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    feats = {ft["id"]: ft for _, ft in all_features(d) if ft.get("id")}
    screens = d.get("screens") or {}
    _, _, _, counts, points = check(d)
    mark = f"<!-- {GEN_MARK} — {t['generated']} -->"

    lines = [f"# {d.get('title', 'Feature list')}", "", mark, "", f"{t['asof']} {d.get('asOf', '')}", ""]
    if d.get("summary"):
        lines += [d["summary"], ""]
    lines += [f"| {t['pr']} | {t['count']} | {t['points']} |", "|---|---|---|"]
    for p in PRS:
        lines.append(f"| {ph[p]} | {counts[p]} | {points[p]} |")
    if counts["exists"]:
        lines.append(f"| {t['exists']} | {counts['exists']} | – |")
    lines.append("")
    bp, how = budget_points(d)
    if bp is not None:
        lines += [f"{t['budget']}: {bp} {t['points']}" + (f" ({how})" if how else ""), ""]
    for g in d.get("groups", []):
        lines += [f"## {g.get('title', '')}", ""]
        if g.get("lead"):
            lines += [g["lead"], ""]
        lines += [f"| {t['feature']} | {t['what']} | {t['pr']} | {t['screen']} |", "|---|---|---|---|"]
        for ft in g.get("features", []):
            desc = esc(ft.get("desc"))
            deps = [feats[x].get("name", x) for x in ft.get("dependsOn") or [] if x in feats]
            if deps:
                desc += "<br>" + ("ต้องมีก่อน" if LANG != "en" else "Needs") + ": " + esc(", ".join(deps))
            if ft.get("seen"):
                desc += f"<br>{t['seen']}: {esc(ft['seen'])}"
            scr = []
            for s in ft.get("screens") or []:
                meta = screens.get(s) or {}
                scr.append(f"{s} ({t['planned']})" if isinstance(meta, dict) and meta.get("drawn") is False else s)
            pr = t["exists"] if is_exists(ft) else short_label(ph.get(ft.get("pr"), ft.get("pr", "")))
            lines.append(f"| {esc(ft.get('name'))} | {desc} | {pr} | {', '.join(scr) or '–'} |")
        lines.append("")

    q = [f"# {t['questions']}", "", mark, ""]
    qs = d.get("questions") or []
    if not qs:
        q.append(t["none"])
    for i, item in enumerate(qs, 1):
        q.append(f"{i}. {item.get('text', '')}")
        if item.get("owner"):
            q.append(f"    - {t['owner']}: {item['owner']}")
        if item.get("due"):
            q.append(f"    - {t['due']}: {item['due']}")
        if item.get("affects"):
            names = [feats[a].get("name", a) if a in feats else a for a in item["affects"]]
            q.append(f"    - {t['affects']}: " + ", ".join(names))

    dl = [f"# {t['decisions']}", "", mark, ""]
    ds = d.get("decisions") or []
    if not ds:
        dl.append(t["none"])
    else:
        dl += [f"| {t['date']} | {t['topic']} | {t['decision']} | {t['why']} |", "|---|---|---|---|"]
        for item in ds:
            dl.append(f"| {esc(item.get('date'))} | {esc(item.get('topic'))} | {esc(item.get('decision'))} | {esc(item.get('why'))} |")
        for item in ds:
            if item.get("options"):
                dl += ["", f"### {item.get('topic', '')}: {t['options']}", "",
                       f"| {t['option']} | {t['pros']} | {t['cons']} |", "|---|---|---|"]
                for o in item["options"]:
                    dl.append(f"| {esc(o.get('name'))} | {esc(o.get('pros'))} | {esc(o.get('cons'))} |")
    if d.get("assumptions"):
        dl += ["", f"## {t['assumptions']}", ""] + [f"- {a}" for a in d["assumptions"]]
    if d.get("sources"):
        dl += ["", f"## {t['sources']}", ""]
        for s in d["sources"]:
            dl.append(f"- [{s['text']}]({s['url']})" if s.get("url") else f"- {s.get('text', '')}")

    files = [(out / "feature-list.md", "\n".join(lines)), (out / "open-questions.md", "\n".join(q) + "\n"),
             (out / "decisions.md", "\n".join(dl) + "\n")]
    # refuse before writing anything, so a partial render never happens
    if not force:
        blocked = [p for p, _ in files if p.exists() and GEN_MARK not in p.read_text(encoding="utf-8", errors="ignore")]
        for p in blocked:
            print(m("refuse", f=p), file=sys.stderr)
        if blocked:
            return 1
    for p, text in files:
        p.write_text(text, encoding="utf-8")
    print(m("wrote", x=", ".join(str(p) for p, _ in files)))
    return 0


